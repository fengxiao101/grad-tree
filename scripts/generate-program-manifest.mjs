import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const groups = [
  { category: 'major', directory: 'majors', index: 'src/data/majors/index.ts' },
  { category: 'minor', directory: 'minors', index: 'src/data/minors/index.ts' },
  { category: 'coterm', directory: 'cotermPrograms', index: 'src/data/cotermPrograms/index.ts' },
];

function quotedField(source, field) {
  const match = source.match(new RegExp(`\\b${field}:\\s*(['"\`])([^'"\`]+)\\1`));
  if (!match) throw new Error(`Could not find ${field}`);
  return match[2];
}

const programs = [];
for (const group of groups) {
  const indexSource = readFileSync(resolve(root, group.index), 'utf8');
  const imports = [...indexSource.matchAll(/import\s+\{\s*(\w+)\s*\}\s+from\s+'\.\/([^']+)'/g)];
  for (const match of imports) {
    const exportName = match[1];
    const moduleName = match[2];
    const relativePath = `./${group.directory}/${moduleName}.ts`;
    const source = readFileSync(resolve(root, 'src/data', group.directory, `${moduleName}.ts`), 'utf8');
    const declarationStart = source.indexOf(`export const ${exportName}`);
    if (declarationStart < 0) throw new Error(`Could not find export ${exportName} in ${relativePath}`);
    const configSource = source.slice(declarationStart);
    programs.push({
      id: quotedField(configSource, 'id'),
      name: quotedField(configSource, 'name'),
      school: quotedField(configSource, 'school'),
      year: quotedField(configSource, 'year'),
      category: group.category,
      modulePath: relativePath,
    });
  }
}

const lines = [
  '// Generated by scripts/generate-program-manifest.mjs. Do not edit by hand.',
  "import type { ProgramSummary } from './programRegistry';",
  '',
  'export const PROGRAM_SUMMARIES: ProgramSummary[] = [',
  ...programs.map(({ modulePath: _modulePath, ...program }) => `  ${JSON.stringify(program)},`),
  '];',
  '',
  'export const PROGRAM_MODULE_PATHS: Record<string, string> = {',
  ...programs.map(program => `  ${JSON.stringify(program.id)}: ${JSON.stringify(program.modulePath)},`),
  '};',
  '',
];

writeFileSync(resolve(root, 'src/data/programManifest.generated.ts'), lines.join('\n'));
console.log(`Generated metadata for ${programs.length} programs.`);
