function concentrationSection(id: string, name: string, courses: CourseOption[]): MajorSection {
  return {
    id: `${id}-courses`,
    name: `${name} Concentration Courses (≥15 units)`,
    minUnits: 15,
    unitOnly: true,
    note: 'At least 15 units for a letter grade, approved by faculty advisor and program director before end of spring quarter of junior year. Subplan is printed on transcript and diploma. Upper-division (100-level) courses preferred. Other courses may be substituted with advisor approval.',
    slots: [
      {
        id: `${id}-pick`,
        label: 'Suggested Concentration Courses',
        type: 'any-approved',
        options: courses,
        note: 'These are suggested courses. Other courses may be taken with faculty advisor approval. Submit the concentration form listing proposed courses and rationale.',
      },
    ],
  };
}

